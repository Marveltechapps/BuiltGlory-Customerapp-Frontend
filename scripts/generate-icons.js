const pascal = name =>
  name
    .split('-')
    .map(s => (s ? s[0].toUpperCase() + s.slice(1) : ''))
    .join('');
const out = {};
const missing = [];
for (const name of [...new Set(NAMES)].sort()) {
  const node = icons[pascal(name)];
  if (!node) {
    missing.push(name);
    continue;
  }
  out[name] = node[2].map(([tag, attrs]) => [tag, attrs]);
}

const header = `// Generated by scripts/generate-icons.js from lucide@0.378.0 (ISC License, https://lucide.dev). Do not edit.\n`;
const body =
  `export type IconElement = [tag: 'path' | 'circle' | 'rect' | 'polyline' | 'line' | 'polygon' | 'ellipse', attrs: Record<string, string | number>];\n\n` +
  `export const ICON_NODES = ${JSON.stringify(out, null, 0).replace(
    /\],"/g,
    '],\n  "',
  )} as const satisfies Record<string, readonly (readonly [string, Record<string, string | number>])[]>;\n\n` +
  `export type IconName = keyof typeof ICON_NODES;\n`;
fs.writeFileSync(
  path.join(__dirname, '..', 'src', 'components', 'iconNodes.ts'),
  header + body,
);
